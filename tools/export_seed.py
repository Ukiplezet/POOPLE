"""Export the word lists embedded in index.html to supabase/seed.sql.

The server checks submitted ladders against the same words and start-word
order that the game uses, so re-run this whenever those lists change:

    python3 tools/export_seed.py
"""
import collections
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
html = (ROOT / "index.html").read_text()


def embedded(pattern):
    return re.search(pattern, html).group(1).split()


words = embedded(r'const WORDS = new Set\("([^"]+)"')
starts = embedded(r'const STARTS = "([^"]+)"')
common = set(embedded(r'const COMMON = new Set\("([^"]+)"'))


def distances(vocab, goal="poop"):
    dist = {goal: 0}
    queue = collections.deque([goal])
    while queue:
        w = queue.popleft()
        for i in range(4):
            for c in "abcdefghijklmnopqrstuvwxyz":
                x = w[:i] + c + w[i + 1:]
                if x in vocab and x not in dist:
                    dist[x] = dist[w] + 1
                    queue.append(x)
    return dist


par = distances(common)
missing = [s for s in starts if s not in par or s not in words]
if missing:
    raise SystemExit(f"start words that can't reach poop: {missing}")

lines = [
    "-- Generated by tools/export_seed.py from index.html. Re-run after changing the word lists.",
    "begin;",
    "truncate public.start_words, public.words;",
]
for k in range(0, len(words), 400):
    chunk = ",\n".join(f"('{w}')" for w in words[k:k + 400])
    lines.append(f"insert into public.words (word) values\n{chunk};")
rows = ",\n".join(f"({i},'{w}',{par[w]})" for i, w in enumerate(starts))
lines.append(f"insert into public.start_words (idx, word, par) values\n{rows};")
lines.append("commit;")

(ROOT / "supabase" / "seed.sql").write_text("\n".join(lines) + "\n")
print(f"wrote {len(words)} words and {len(starts)} start words")
